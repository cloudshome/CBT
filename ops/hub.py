"""P19 — Ubuntu SKY Hub: layout, first-run, backup/restore, doctor.

This module is the production-install brain. It never places an exchange
order and never moves a graduation/risk threshold. Paths default to the
FHS layout used by the Debian package:

    /opt/sky          immutable application tree
    /etc/sky          configuration (mode 0750, files 0640)
    /var/lib/sky      database, Parquet store, backups
    journald          logs (no secrets)

Tests override the roots via ``SKY_HUB_PREFIX`` so the same code runs
offline without installing a package or talking to systemd.
"""
