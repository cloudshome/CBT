def _env_path(name: str, default: str) -> Path:
    return Path(os.getenv(name, default))


@dataclass
class HubPaths:
    """FHS roots, overridable for tests via SKY_HUB_PREFIX."""

    prefix: Path
    opt: Path
    etc: Path
    var: Path

    @classmethod
    def resolve(cls, prefix: Path | str | None = None) -> "HubPaths":
        if prefix is None:
            raw = os.getenv("SKY_HUB_PREFIX", "")
            prefix = Path(raw) if raw else Path("/")
        prefix = Path(prefix)
        if str(prefix) in ("", "/"):
            return cls(prefix=Path("/"),
                       opt=Path("/opt/sky"),
                       etc=Path("/etc/sky"),
                       var=Path("/var/lib/sky"))
        return cls(prefix=prefix,
                   opt=prefix / "opt" / "sky",
                   etc=prefix / "etc" / "sky",
                   var=prefix / "var" / "lib" / "sky")

    @property
    def env_file(self) -> Path:
        return self.etc / "sky.env"

    @property
    def setup_stamp(self) -> Path:
        return self.etc / "setup.json"

    @property
    def db_path(self) -> Path:
        return self.var / "cryptobrain.db"

    @property
    def store_dir(self) -> Path:
        return self.var / "store"

    @property
    def backup_dir(self) -> Path:
        return self.var / "backups"


