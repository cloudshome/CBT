ENFORCE_RISK_LIMITS=true
TRADER_STATE_BLOCK=true
RISK_PCT=0.5
MAX_DAILY_LOSS_PCT=1.5
MAX_WEEKLY_LOSS_PCT=3.0
GOLD_SESSION_MODE=block
GOLD_NEWS_BLOCK=true
