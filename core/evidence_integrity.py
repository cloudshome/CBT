"""
Evidence Integrity Layer — provenance tracking for every probability the desk emits.

Motivation
----------
Several engines in this platform degrade gracefully by *fabricating* data when
real data is unavailable:

  * ``data_streamer.get_candles()``    -> ``generate_synthetic_candles()`` (np.random walk)
  * ``analogue_engine.find_analogues()`` -> ``_generate_synthetic_historical_states()``
  * ``institutional_alpha``/``lead_lag_correlator`` -> np.random fallback series

Graceful degradation is fine for a *chart*. It is catastrophic for a *decision*,
because the fabricated numbers flow into ``p_tp_hit`` -> ``net_ev`` ->
``conservative_kelly`` -> position size, and arrive at the operator wearing the
same clothes as real empirical evidence.

Concretely (measured on a cold database):
    real historical states available : 0
    k_samples_found                  : 50      <- all synthetic
    sample_adequacy_score            : 1.00    <- claims "fully adequate"
    uncertainty_penalty              : 0.00    <- claims "no penalty"

The system reported maximum confidence in a number derived entirely from
``np.random.seed(1337)``.

This module provides the vocabulary and the enforcement primitive to make that
class of bug structurally impossible: evidence must *declare its origin*, and
fabricated evidence can never satisfy a live-decision gate.

Design contract
---------------
1. ``EvidenceGrade`` — every probability/statistic carries a provenance grade.
2. ``EvidenceLedger`` — accumulates grades across a decision pipeline; the
   decision inherits the *worst* grade in its inputs (weakest-link semantics).
3. ``require_live_evidence()`` — a hard gate. Synthetic-backed evidence cannot
   authorize anything other than NO_TRADE.

This layer is intentionally dependency-free (stdlib only) so it can be imported
by any engine without creating import cycles.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import IntEnum
from typing import Any

__all__ = [
    "EVIDENCE_KEY",
    "EvidenceGrade",
    "EvidenceLedger",
    "EvidenceViolation",
    "grade_of",
    "require_live_evidence",
    "stamp_records",
    "weakest_grade",
]

EVIDENCE_KEY = "evidence_grade"
"""Canonical key carrying provenance on every market-data record."""


class EvidenceGrade(IntEnum):
    """
    Provenance grade of a statistic. Ordered: lower == less trustworthy.

    The ordering matters — ``min()`` over a set of grades yields the
    weakest link, which is the only honest grade for a derived quantity.
    """

    FABRICATED = 0
    """Generated by a random process. Carries zero information about the market.
    Legal for UI smoke-tests and cold-start rendering. Never legal for sizing."""

    SIMULATED = 1
    """Derived from a model/bootstrap over real inputs (e.g. Monte Carlo paths).
    Informative, but not an out-of-sample empirical observation."""

    IMPUTED = 2
    """Real data with gaps filled/interpolated, or a small-sample estimate below
    the statistical adequacy threshold."""

    EMPIRICAL = 3
    """Observed market data with sufficient sample size. The only grade that may
    authorize risk."""

    @property
    def label(self) -> str:
        return self.name

    @property
    def is_tradeable(self) -> bool:
        """Only genuine empirical observation may authorize risk."""
        return self is EvidenceGrade.EMPIRICAL


class EvidenceViolation(RuntimeError):
    """Raised when non-empirical evidence is used to authorize risk."""


@dataclass
class EvidenceLedger:
    """
    Accumulates evidence provenance across a decision pipeline.

    Weakest-link semantics: a decision is only as trustworthy as its least
    trustworthy input. One fabricated series contaminates the whole verdict,
    and this ledger refuses to let that fact get lost between layers.

    Example
    -------
    >>> led = EvidenceLedger()
    >>> led.record("candles", EvidenceGrade.EMPIRICAL, sample_size=500)
    >>> led.record("analogues", EvidenceGrade.FABRICATED, sample_size=50,
    ...            note="cold brain_memory.db; synthetic states seeded")
    >>> led.grade
    <EvidenceGrade.FABRICATED: 0>
    >>> led.is_tradeable
    False
    """

    entries: list[dict[str, Any]] = field(default_factory=list)

    def record(
        self,
        source: str,
        grade: EvidenceGrade,
        *,
        sample_size: int | None = None,
        note: str = "",
    ) -> None:
        """Register one evidence input into the ledger."""
        self.entries.append(
            {
                "source": source,
                "grade": grade,
                "grade_label": grade.label,
                "sample_size": sample_size,
                "note": note,
            }
        )

    @property
    def grade(self) -> EvidenceGrade:
        """The weakest grade recorded. Empty ledger == nothing proven == FABRICATED."""
        if not self.entries:
            return EvidenceGrade.FABRICATED
        return min(e["grade"] for e in self.entries)

    @property
    def is_tradeable(self) -> bool:
        return self.grade.is_tradeable

    @property
    def contaminated_sources(self) -> list[str]:
        """Sources responsible for dragging the ledger below EMPIRICAL."""
        worst = self.grade
        return [e["source"] for e in self.entries if e["grade"] == worst and not worst.is_tradeable]

    def reason(self) -> str:
        """Operator-facing explanation of why this decision is or isn't tradeable."""
        if self.is_tradeable:
            return "All inputs empirically grounded."
        bad = self.contaminated_sources
        return (
            f"Evidence grade {self.grade.label}: "
            f"{', '.join(bad) if bad else 'no evidence recorded'} "
            f"{'is' if len(bad) == 1 else 'are'} not empirically grounded."
        )

    def to_dict(self) -> dict[str, Any]:
        """Serialized form for API responses and the audit bus."""
        return {
            "evidence_grade": self.grade.label,
            "is_tradeable": self.is_tradeable,
            "reason": self.reason(),
            "contaminated_sources": self.contaminated_sources,
            "entries": [
                {
                    "source": e["source"],
                    "grade": e["grade_label"],
                    "sample_size": e["sample_size"],
                    "note": e["note"],
                }
                for e in self.entries
            ],
        }


def require_live_evidence(ledger: EvidenceLedger, action: str) -> None:
    """
    Hard gate for any code path that commits capital.

    Call this immediately before sizing, order submission, or promoting a
    strategy tier. Raises rather than returning a flag, because a boolean
    return is too easy to ignore at a call site.

    Raises
    ------
    EvidenceViolation
        If any input to the decision is below ``EvidenceGrade.EMPIRICAL``.
    """
    if not ledger.is_tradeable:
        raise EvidenceViolation(f"Refusing to {action}. {ledger.reason()}")


# ---------------------------------------------------------------------------
# Record-level provenance stamping
# ---------------------------------------------------------------------------
#
# Architectural rule: PROVENANCE IS IMMUTABLE AT THE BOUNDARY.
#
# Downstream code must never be able to take a FABRICATED record and turn it
# into an EMPIRICAL one. The laundering bug this guards against was exactly
# that: ``SyntheticMarketProvider`` emitted untagged random candles and
# ``data_streamer`` then stamped ``is_synthetic = 0`` over everything the
# gateway returned, permanently persisting noise as observed market data.
#
# ``stamp_records`` therefore only ever *downgrades*. Attempting to raise a
# record's grade is silently refused — the weaker grade wins, always.


def _explicit_grade(record: dict[str, Any]) -> EvidenceGrade | None:
    """Grade already recorded on this record, or ``None`` if never stamped."""
    raw = record.get(EVIDENCE_KEY)
    if isinstance(raw, EvidenceGrade):
        return raw
    if isinstance(raw, str):
        try:
            return EvidenceGrade[raw]
        except KeyError:
            return EvidenceGrade.FABRICATED
    legacy = record.get("is_synthetic")
    if legacy is not None:
        return EvidenceGrade.FABRICATED if int(legacy) == 1 else EvidenceGrade.EMPIRICAL
    return None


def grade_of(record: dict[str, Any]) -> EvidenceGrade:
    """
    Read the provenance grade off a single market-data record.

    Records with no grade are treated as ``FABRICATED``, not as empirical.
    Untagged data is untrusted data — the safe default is the strict one, so
    that a provider which forgets to stamp its output cannot thereby produce
    tradeable evidence.
    """
    # Legacy ``is_synthetic`` rows are honoured for backwards compatibility.
    explicit = _explicit_grade(record)
    return EvidenceGrade.FABRICATED if explicit is None else explicit


def stamp_records(
    records: list[dict[str, Any]],
    grade: EvidenceGrade,
) -> list[dict[str, Any]]:
    """
    Stamp provenance onto market-data records, in place, downgrade-only.

    If a record already carries a *weaker* grade than ``grade``, the weaker
    grade is preserved. This makes the laundering bug unrepresentable: no
    call site can promote synthetic data to empirical, however it is written.

    The legacy ``is_synthetic`` flag is kept in sync so existing SQL filters
    and dashboards continue to work, but it is no longer the security
    boundary — ``EVIDENCE_KEY`` is.
    """
    for rec in records:
        prior = _explicit_grade(rec)
        # An unstamped record is being labelled for the first time by the
        # component that produced it, so it takes ``grade`` directly. An
        # already-stamped record can only ever move downwards.
        effective = grade if prior is None else min(grade, prior)
        rec[EVIDENCE_KEY] = effective.label
        rec["is_synthetic"] = 0 if effective is EvidenceGrade.EMPIRICAL else 1
    return records


def weakest_grade(records: list[dict[str, Any]]) -> EvidenceGrade:
    """
    Weakest-link grade across a series.

    An empty series proves nothing and therefore grades ``FABRICATED``. One
    fabricated bar in an otherwise clean series contaminates the whole series,
    because an indicator computed over it is contaminated too.
    """
    if not records:
        return EvidenceGrade.FABRICATED
    return min(grade_of(r) for r in records)
