"""
core/intelligence/evolution_shield.py
=====================================
Senior Quantitative Systems Architecture — Evolution Shield & Anti-Poisoning Engine.

Core Mandate:
Prevents automated AI research and self-evolution systems from poisoning the platform
with curve-fitted, over-fitted, or risk-diluting rules derived from past trade autopsies.

Architectural Defense Layers:
1. Constitutional Prohibition Linter:
   Blocks any proposal that widens stop losses, increases leverage, relaxes risk ceilings,
   bypasses daily loss limits, or overrides deterministic circuit breakers.
2. Sample Size & Empirical Hurdle:
   Rejects single-event trauma (e.g., reacting to one flash crash).
   Requires minimum sample size N >= 30 distinct historical observations.
3. Epistemic Demotion Firewall:
   A self-evolution lesson can NEVER modify live trading parameters directly.
   It can only be emitted as a NON_EXECUTABLE_RESEARCH_HYPOTHESIS candidate for
   formal Out-of-Sample Walk-Forward validation in the Strategy League.
4. Permanent Capital Firewall:
   real_capital_enabled = False permanent.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Any

logger = logging.getLogger("ai_quant_sentinel.intelligence.evolution_shield")

REAL_CAPITAL_ENABLED: bool = False


class LessonVerdict(str, Enum):
    APPROVED_CANDIDATE = "APPROVED_CANDIDATE"
    REJECTED_TOXIC_RISK = "REJECTED_TOXIC_RISK"
    REJECTED_INSUFFICIENT_SAMPLE = "REJECTED_INSUFFICIENT_SAMPLE"
    REJECTED_SINGLE_EVENT_TRAUMA = "REJECTED_SINGLE_EVENT_TRAUMA"
    REJECTED_EXECUTION_OVERRIDE = "REJECTED_EXECUTION_OVERRIDE"


@dataclass
class ProposedLesson:
    """A candidate lesson generated by an AI research autopsy or self-evolution pass."""

    lesson_id: str
    proposed_rule: str
    rationale: str
    trigger_trade_ids: list[str]
    sample_size: int
    asset_scope: list[str] = field(default_factory=lambda: ["ALL"])
    target_regime: str = "ALL"
    requested_stop_loss_pct_change: float = 0.0  # > 0 means widening stop loss
    requested_leverage_multiplier: float = 1.0   # > 1.0 means increasing leverage
    attempts_risk_relaxation: bool = False
    attempts_execution_mutation: bool = False


@dataclass
class EvolutionShieldVerdict:
    """Deterministic verdict emitted by the Evolution Shield."""

    verdict: LessonVerdict
    is_safe: bool
    rejection_reasons: list[str]
    promoted_status: str
    sanitized_hypothesis: str | None = None
    real_capital_enabled: bool = False


class EvolutionShield:
    """
    Multi-Layer Anti-Poisoning & Self-Evolution Guardian.
    """

    MINIMUM_SAMPLE_SIZE: int = 30  # Minimum statistical power threshold

    # Regex patterns detecting toxic risk dilution or defeatism
    TOXIC_PATTERNS = [
        (re.compile(r"\b(widen|increase|expand|loosen)\s+(the\s+)?(stop|sl|invalidation)\b", re.IGNORECASE), "Prohibited: Widening stop-loss limits."),
        (re.compile(r"\b(increase|boost|raise|double)\s+(the\s+)?(leverage|margin|notional|risk)\b", re.IGNORECASE), "Prohibited: Increasing leverage or risk exposure."),
        (re.compile(r"\b(disable|bypass|ignore|override)\s+(the\s+)?(risk|circuit|breaker|kill[- ]?switch|limit)\b", re.IGNORECASE), "Prohibited: Bypassing risk controls or kill switches."),
        (re.compile(r"\bnever\s+(go\s+)?(long|buy)\s+(btc|eth|crypto)\s+again\b", re.IGNORECASE), "Prohibited: Permanent asymmetric directional defeatism."),
        (re.compile(r"\bnever\s+(go\s+)?(short|sell)\s+(btc|eth|crypto)\s+again\b", re.IGNORECASE), "Prohibited: Permanent asymmetric directional defeatism."),
        (re.compile(r"\b(double\s+down|martingale|average\s+down)\b", re.IGNORECASE), "Prohibited: Martingale or loss averaging heuristics."),
    ]

    def __init__(self, min_sample_size: int = MINIMUM_SAMPLE_SIZE) -> None:
        self.min_sample_size = min_sample_size
        self.real_capital_enabled: bool = False

    def evaluate_lesson(self, lesson: ProposedLesson) -> EvolutionShieldVerdict:
        """
        Interrogates a proposed AI lesson across all 4 defense layers.
        """
        rejection_reasons: list[str] = []

        # Layer 1: Toxic Parameter Modifications
        if lesson.requested_stop_loss_pct_change > 0:
            rejection_reasons.append("Rejected: Direct request to widen stop-loss invalidation distance.")
        if lesson.requested_leverage_multiplier > 1.0:
            rejection_reasons.append(f"Rejected: Request to increase leverage by {lesson.requested_leverage_multiplier}x.")
        if lesson.attempts_risk_relaxation:
            rejection_reasons.append("Rejected: Flagged as attempting risk ceiling relaxation.")
        if lesson.attempts_execution_mutation:
            rejection_reasons.append("Rejected: AI lessons cannot directly alter execution order routers.")

        # Layer 1b: Toxic Language / Pattern Inspection
        full_text = f"{lesson.proposed_rule} {lesson.rationale}"
        for pattern, explanation in self.TOXIC_PATTERNS:
            if pattern.search(full_text):
                rejection_reasons.append(explanation)

        if rejection_reasons:
            logger.warning(
                "EvolutionShield BLOCKED toxic lesson %s: %s",
                lesson.lesson_id,
                rejection_reasons,
            )
            return EvolutionShieldVerdict(
                verdict=LessonVerdict.REJECTED_TOXIC_RISK,
                is_safe=False,
                rejection_reasons=rejection_reasons,
                promoted_status="QUARANTINED_TOXIC_LESSON",
                real_capital_enabled=False,
            )

        # Layer 2: Single-Event Trauma Check
        if len(lesson.trigger_trade_ids) <= 1:
            rejection_reasons.append(
                f"Rejected: Single-event reaction. Rule triggered by only {len(lesson.trigger_trade_ids)} trade(s)."
            )
            return EvolutionShieldVerdict(
                verdict=LessonVerdict.REJECTED_SINGLE_EVENT_TRAUMA,
                is_safe=False,
                rejection_reasons=rejection_reasons,
                promoted_status="REJECTED_EVENT_TRAUMA",
                real_capital_enabled=False,
            )

        # Layer 3: Sample Size & Empirical Power Check
        if lesson.sample_size < self.min_sample_size:
            rejection_reasons.append(
                f"Rejected: Insufficient sample size (N={lesson.sample_size} < required {self.min_sample_size})."
            )
            return EvolutionShieldVerdict(
                verdict=LessonVerdict.REJECTED_INSUFFICIENT_SAMPLE,
                is_safe=False,
                rejection_reasons=rejection_reasons,
                promoted_status="PENDING_FURTHER_OBSERVATIONS",
                real_capital_enabled=False,
            )

        # Layer 4: Safe Candidate Promotion
        sanitized_hypothesis = (
            f"HYPOTHESIS [{lesson.lesson_id}]: {lesson.proposed_rule.strip()} "
            f"(Conditioned on regime={lesson.target_regime}, N={lesson.sample_size})"
        )

        logger.info(
            "EvolutionShield APPROVED research hypothesis candidate %s (N=%d)",
            lesson.lesson_id,
            lesson.sample_size,
        )

        return EvolutionShieldVerdict(
            verdict=LessonVerdict.APPROVED_CANDIDATE,
            is_safe=True,
            rejection_reasons=[],
            promoted_status="PROMOTED_TO_RESEARCH_HYPOTHESIS_QUEUE",
            sanitized_hypothesis=sanitized_hypothesis,
            real_capital_enabled=False,
        )
