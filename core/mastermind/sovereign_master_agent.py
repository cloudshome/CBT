    async def _analyze_live_telemetry(self, symbol: str) -> dict[str, Any]:
        """
        Fetches live candles, order flow CVD, and derivatives telemetry.
        Evaluates the 12-Stage SKY Structural Intelligence Engine.
        """
        norm_sym = normalize_symbol(symbol)

        # 1. Fetch live 15m candles
        try:
            candles_15m = await data_streamer.fetch_external_ohlcv(norm_sym, "15m", limit=60)
        except Exception:
            candles_15m = data_streamer.get_candles(norm_sym, "15m", limit=60)

        if not candles_15m or len(candles_15m) < 15:
            # Fallback to local cache
            candles_15m = data_streamer.get_candles(norm_sym, "15m", limit=60)

        # 2. Compile Multi-Timeframe Context
        tf_map: dict[str, list[dict[str, Any]]] = {"15m": candles_15m}
        for tf in ("1h", "4h", "5m"):
            cached_tf = data_streamer.get_candles(norm_sym, tf, limit=30)
            if not cached_tf or len(cached_tf) < 15:
                try:
                    fresh = await data_streamer.fetch_external_ohlcv(norm_sym, tf, limit=30)
                    if fresh:
                        cached_tf = fresh
                except Exception:
                    pass
            tf_map[tf] = cached_tf

        # 3. Evaluate 12-stage SKY Engine
        decision_out = sky_orchestrator.analyze_market(
            symbol=norm_sym,
            timeframe="15m",
            candles=candles_15m,
            candles_by_tf=tf_map,
            account_equity_usd=self.account_equity_usd,
        )

        cur_price = float(candles_15m[-1]["close"]) if candles_15m else 0.0

        # Extract regime metrics
        dossier = decision_out.explanation_dossier
        regime_info = dossier.get("regime_state", {})
        adx_val = float(regime_info.get("trend_strength_adx", 25.0))
        regime_name = str(regime_info.get("regime_type", "CONSOLIDATION"))

        vol_info = dossier.get("volume", {})
        rvol = float(vol_info.get("relative_volume", 1.0)) if isinstance(vol_info, dict) else 1.0

        return {
            "current_price": cur_price,
            "candles_count": len(candles_15m),
            "sky_decision": decision_out,
            "adx": adx_val,
            "regime": regime_name,
            "rvol": rvol,
        }

