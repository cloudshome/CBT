    def _query_asset_memory(self, symbol: str) -> dict[str, Any]:
        """
        Queries historical SQLite shadow positions for performance patterns,
        win rates, and past failure causes for this asset.
        """
        norm_sym = normalize_symbol(symbol)
        with db_manager.get_trading_conn() as conn:
            cur = conn.cursor()
            cur.execute(
                """
                SELECT 
                    COUNT(*) as total_trades,
                    SUM(CASE WHEN realized_pnl > 0 THEN 1 ELSE 0 END) as wins,
                    SUM(CASE WHEN realized_pnl <= 0 THEN 1 ELSE 0 END) as losses,
                    SUM(realized_pnl) as net_pnl,
                    AVG(CASE WHEN realized_pnl > 0 THEN realized_pnl ELSE NULL END) as avg_win,
                    AVG(CASE WHEN realized_pnl < 0 THEN realized_pnl ELSE NULL END) as avg_loss
                FROM shadow_positions
                WHERE symbol = ? AND status = 'CLOSED';
                """,
                (norm_sym,),
            )
            row = cur.fetchone()
            total_trades = row["total_trades"] or 0
            wins = row["wins"] or 0
            losses = row["losses"] or 0
            net_pnl = round(float(row["net_pnl"] or 0.0), 2)
            avg_win = round(float(row["avg_win"] or 0.0), 2)
            avg_loss = round(float(row["avg_loss"] or 0.0), 2)
            win_rate = round((wins / total_trades) * 100.0, 1) if total_trades > 0 else 0.0

            # Query last 3 closed trades
            cur.execute(
                """
                SELECT position_id, direction, entry_price, current_price, realized_pnl, exit_reason
                FROM shadow_positions
                WHERE symbol = ? AND status = 'CLOSED'
                ORDER BY closed_at DESC LIMIT 3;
                """,
                (norm_sym,),
            )
            recent_trades = [dict(r) for r in cur.fetchall()]

        # Asset-specific empirical memory guidance derived from the 419-trade dataset
        guidance = ""
        risk_adjustment_factor = 1.0

        if "BTC" in norm_sym:
            guidance = (
                f"Historical Edge Validated: {total_trades} trades, {win_rate}% win rate, net PnL: ${net_pnl:+.2f}. "
                "BTC performs best on 4H trend pullbacks with positive CVD absorption. "
                "Safe to trade institutional setups with standard Half-Kelly allocation."
            )
            risk_adjustment_factor = 1.0
        elif "ETH" in norm_sym:
            guidance = (
                f"Historical Drawdown Caution: {total_trades} trades, {win_rate}% win rate, net PnL: ${net_pnl:+.2f}. "
                "CRITICAL WARNING: ETH has suffered severe chop bleed from taking early breakouts in low-volatility ranges. "
                "MANDATORY REQUIREMENT: Require trend ADX >= 22.0 and relative volume >= 1.1x to clear any trade."
            )
            risk_adjustment_factor = 0.65  # Conservative discount on ETH until out-of-sample edge turns positive
        elif "XAU" in norm_sym or "PAXG" in norm_sym:
            guidance = (
                f"Historical Edge Validated: {total_trades} trades, {win_rate}% win rate, net PnL: ${net_pnl:+.2f}. "
                "Gold demonstrates strong edge on session extreme liquidity sweeps and mean-reversions. "
                "Maintain minimum 2.0R asymmetric take-profit targets."
            )
            risk_adjustment_factor = 1.0

        return {
            "symbol": norm_sym,
            "total_trades": total_trades,
            "wins": wins,
            "losses": losses,
            "win_rate_pct": win_rate,
            "net_pnl_usd": net_pnl,
            "avg_win_usd": avg_win,
            "avg_loss_usd": avg_loss,
            "recent_trades": recent_trades,
            "memory_guidance": guidance,
            "risk_adjustment_factor": risk_adjustment_factor,
        }

