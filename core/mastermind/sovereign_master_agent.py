    async def execute_master_decision(
        self, symbol: str, override_reason: str | None = None
    ) -> dict[str, Any]:
        """
        Instantly analyzes the asset and executes an authorized position into
        portfolio_shadow and mirrors to Binance Futures Testnet if qualified.
        """
        decision = await self.synthesize_asset(symbol)

        if decision.decision == "CASH":
            return {
                "success": False,
                "executed": False,
                "action": "CASH",
                "symbol": decision.symbol,
                "reason": decision.thesis,
                "decision": decision.to_dict(),
            }

        # Open Position in Authoritative Shadow Ledger
        direction_str = "LONG" if decision.decision == "BUY" else "SHORT"
        tp_primary = decision.take_profit_ladder.get("tp1", decision.current_price * 1.04)

        reason_desc = (
            f"[SOVEREIGN_MASTER] {decision.symbol} {direction_str} | "
            f"EV: +{decision.expected_value_r:.2f}R | "
            f"Conf: {decision.confidence_pct:.0f}%"
        )
        if override_reason:
            reason_desc += f" | {override_reason}"

        pos_id = portfolio_shadow.open_position(
            symbol=decision.symbol,
            direction=direction_str,
            size=decision.suggested_units,
            entry_price=decision.current_price,
            stop_loss=decision.stop_loss,
            take_profit=tp_primary,
            entry_reason=reason_desc,
            enforce_atomic_limits=True,
            max_risk_usd=decision.suggested_risk_usd,
        )

        # Mirror to Binance Futures Testnet (active with $5,000 USDT)
        mirrored_ok = False
        mirror_err = None
        try:
            from core.auth.credential_vault import credential_vault
            from core.execution.live_canary_runner import CanaryRunRequest, live_canary_runner

            cred = credential_vault.get_credential("BINANCE_FUTURES", "TESTNET")
            if cred and cred.is_active:
                req = CanaryRunRequest(
                    exchange="BINANCE_FUTURES",
                    symbol=decision.symbol.replace("/", ""),
                    notional_usd=min(25.0, decision.suggested_units * decision.current_price),
                    side="BUY" if direction_str == "LONG" else "SELL",
                    stop_loss_price=decision.stop_loss,
                    is_dry_run=False,
                    environment="TESTNET",
                )
                res = await live_canary_runner.execute_canary_order(req)
                mirrored_ok = res.success
        except Exception as ex:
            mirror_err = str(ex)

        return {
            "success": True,
            "executed": True,
            "action": decision.decision,
            "position_id": pos_id,
            "symbol": decision.symbol,
            "units": decision.suggested_units,
            "entry_price": decision.current_price,
            "stop_loss": decision.stop_loss,
            "take_profit": tp_primary,
            "risk_reward_ratio": decision.risk_reward_ratio,
            "mirrored_to_binance_testnet": mirrored_ok,
            "binance_mirror_error": mirror_err,
            "thesis": decision.thesis,
            "decision": decision.to_dict(),
        }

