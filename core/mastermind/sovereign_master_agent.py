def normalize_symbol(sym: str) -> str:
    """Normalizes symbol to standardized slash-separated format."""
    clean = sym.strip().upper()
    if "/" in clean:
        return clean
    if clean in ("BTCUSDT", "BTC"):
        return "BTC/USDT"
    if clean in ("ETHUSDT", "ETH"):
        return "ETH/USDT"
    if clean in ("XAUUSD", "XAU", "GOLD"):
        return "XAU/USD"
    if clean in ("PAXGUSDT", "PAXG"):
        return "PAXG/USDT"
    return clean


