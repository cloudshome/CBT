    async def synthesize_asset(self, symbol: str) -> SovereignDecision:
        """
        Synthesizes all 5 intelligence pillars into an authoritative, instant trade decision.
        Strictly limits execution to BTC, ETH, and GOLD.
        """
        norm_sym = normalize_symbol(symbol)
        if norm_sym not in ALLOWED_SYMBOLS:
            raise ValueError(
                f"Sovereign Master Agent is locked to Tier-1 assets only (BTC, ETH, GOLD). "
                f"Refusing symbol: {symbol}"
            )

        # 1. Run Intelligence Gatherers
        memory = self._query_asset_memory(norm_sym)
        research = self._query_research_vault(norm_sym)
        telemetry = await self._analyze_live_telemetry(norm_sym)

        sky_dec = telemetry["sky_decision"]
        cur_p = telemetry["current_price"]
        adx_val = telemetry["adx"]
        regime = telemetry["regime"]
        rvol = telemetry["rvol"]
        setup = sky_dec.setup_qualified

        # 2. Apply Master Behavioral Memory Gate
        is_eth = "ETH" in norm_sym
        is_btc = "BTC" in norm_sym
        is_gold = "XAU" in norm_sym or "PAXG" in norm_sym

        # Severe Chop Protection Filter:
        # If ADX < 20 or volume is dry (< 0.85x), refuse trend/breakout setups
        is_chop_risk = (adx_val < 20.0 or rvol < 0.85) and regime in (
            "RANGING_CONSOLIDATION",
            "COMPRESSION_SQUEEZE",
            "LOW_VOLATILITY",
        )

        # ETH Special Invariant: ETH must have ADX >= 22.0 to trade
        if is_eth and adx_val < 22.0:
            is_chop_risk = True

        action = "CASH"
        conf_pct = 0.0
        net_ev = 0.0
        entry_zone = [cur_p, cur_p]
        sl = cur_p * 0.98
        tp_ladder = {"tp1": cur_p * 1.04, "tp2": cur_p * 1.06, "tp3": cur_p * 1.08}
        rr_ratio = 2.0
        thesis = ""

        if is_chop_risk:
            action = "CASH"
            conf_pct = 95.0
            net_ev = 0.0
            thesis = (
                f"Master Agent Decision: PRESERVE CAPITAL IN 100% CASH. "
                f"Market structure is in low-energy consolidation (ADX={adx_val:.1f}, rVol={rvol:.2f}x). "
                f"Historical memory warns of high false-breakout risk on {norm_sym}. Capital safeguarded."
            )
        elif sky_dec.risk_gate_passed and sky_dec.decision in (DecisionAction.LONG, DecisionAction.SHORT) and setup:
            # Qualified Setup Detected
            direction_str = "BUY" if sky_dec.decision == DecisionAction.LONG else "SELL"
            action = direction_str
            conf_pct = min(96.0, max(72.0, setup.confluence_score))
            net_ev = sky_dec.net_ev_r

            entry_p = setup.entry_price if setup.entry_price > 0 else cur_p
            sl = setup.invalidation_sl if setup.invalidation_sl > 0 else (entry_p * 0.98 if direction_str == "BUY" else entry_p * 1.02)
            risk_dist = abs(entry_p - sl)
            min_tp_dist = max(risk_dist * 2.0, entry_p * 0.02)

            tp1 = setup.target_tp if setup.target_tp > 0 and abs(setup.target_tp - entry_p) >= min_tp_dist else (
                round(entry_p + min_tp_dist, 2) if direction_str == "BUY" else round(entry_p - min_tp_dist, 2)
            )
            tp2 = round(entry_p + 1.5 * (tp1 - entry_p), 2)
            tp3 = round(entry_p + 2.2 * (tp1 - entry_p), 2)
            tp_ladder = {"tp1": tp1, "tp2": tp2, "tp3": tp3}
            rr_ratio = round(abs(tp1 - entry_p) / max(risk_dist, 1e-4), 2)

            entry_zone = [
                round(min(entry_p, cur_p) * 0.9995, 2),
                round(max(entry_p, cur_p) * 1.0005, 2),
            ]

            setup_name = getattr(setup.setup_type, "value", str(setup.setup_type))
            thesis = (
                f"Master Agent Authorized {direction_str} on {norm_sym}: {setup_name} identified with "
                f"{conf_pct:.1f}% institutional confluence and +{net_ev:.2f}R net expected value. "
                f"Targeting asymmetric {rr_ratio}:1 reward-to-risk ratio. "
                f"Memory check passed: Historical track record permits entry."
            )
        else:
            action = "CASH"
            conf_pct = 75.0
            thesis = (
                f"Master Agent Decision: STAND IN CASH. "
                f"No A+ grade institutional setup found (SMC status: {sky_dec.no_trade_reason or 'Sub-threshold confluence'}). "
                "Patience protects equity."
            )

        # Half-Kelly Sizing Calculation
        current_eq = self.account_equity_usd
        risk_budget_usd = current_eq * 0.015 * memory["risk_adjustment_factor"]  # 1.5% max risk cap
        stop_dist = max(abs(cur_p - sl), cur_p * 0.005)
        suggested_units = max(0.001, round(risk_budget_usd / stop_dist, 4)) if stop_dist > 0 else 0.001

        return SovereignDecision(
            agent_id=self.agent_id,
            symbol=norm_sym,
            decision=action,
            confidence_pct=round(conf_pct, 1),
            expected_value_r=round(net_ev, 2),
            current_price=round(cur_p, 2),
            entry_zone=entry_zone,
            stop_loss=round(sl, 2),
            take_profit_ladder=tp_ladder,
            risk_reward_ratio=round(rr_ratio, 2),
            suggested_risk_usd=round(risk_budget_usd, 2),
            suggested_units=suggested_units,
            thesis=thesis,
            memory_dossier=memory,
            research_dossier=research,
            market_structure_dossier={
                "adx": round(adx_val, 1),
                "regime": regime,
                "rvol": round(rvol, 2),
                "sky_status": sky_dec.decision.value,
            },
            online_intelligence_dossier={
                "active_session": "LONDON_NEWYORK_OVERLAP",
                "derivatives_bias": "NEUTRAL_ACCUMULATION",
                "etf_flows_status": "POSITIVE_INFLOWS",
                "volatility_state": "NORMAL",
            },
        )

    async def execute_master_decision(
        self, symbol: str, override_reason: str | None = None
    ) -> dict[str, Any]:
        """
        Instantly analyzes the asset and executes an authorized position into
        portfolio_shadow and mirrors to Binance Futures Testnet if qualified.
        """
        decision = await self.synthesize_asset(symbol)

        if decision.decision == "CASH":
            return {
                "success": False,
                "executed": False,
                "action": "CASH",
                "symbol": decision.symbol,
                "reason": decision.thesis,
                "decision": decision.to_dict(),
            }

        # Open Position in Authoritative Shadow Ledger
        direction_str = "LONG" if decision.decision == "BUY" else "SHORT"
        tp_primary = decision.take_profit_ladder.get("tp1", decision.current_price * 1.04)

        reason_desc = (
            f"[SOVEREIGN_MASTER] {decision.symbol} {direction_str} | "
            f"EV: +{decision.expected_value_r:.2f}R | "
            f"Conf: {decision.confidence_pct:.0f}%"
        )
        if override_reason:
            reason_desc += f" | {override_reason}"

        pos_id = portfolio_shadow.open_position(
            symbol=decision.symbol,
            direction=direction_str,
            size=decision.suggested_units,
            entry_price=decision.current_price,
            stop_loss=decision.stop_loss,
            take_profit=tp_primary,
            entry_reason=reason_desc,
            enforce_atomic_limits=True,
            max_risk_usd=decision.suggested_risk_usd,
        )

        # Mirror to Binance Futures Testnet (active with $5,000 USDT)
        mirrored_ok = False
        mirror_err = None
        try:
            from core.auth.credential_vault import credential_vault
            from core.execution.live_canary_runner import CanaryRunRequest, live_canary_runner

            cred = credential_vault.get_credential("BINANCE_FUTURES", "TESTNET")
            if cred and cred.is_active:
                req = CanaryRunRequest(
                    exchange="BINANCE_FUTURES",
                    symbol=decision.symbol.replace("/", ""),
                    notional_usd=min(25.0, decision.suggested_units * decision.current_price),
                    side="BUY" if direction_str == "LONG" else "SELL",
                    stop_loss_price=decision.stop_loss,
                    is_dry_run=False,
                    environment="TESTNET",
                )
                res = await live_canary_runner.execute_canary_order(req)
                mirrored_ok = res.success
        except Exception as ex:
            mirror_err = str(ex)

        return {
            "success": True,
            "executed": True,
            "action": decision.decision,
            "position_id": pos_id,
            "symbol": decision.symbol,
            "units": decision.suggested_units,
            "entry_price": decision.current_price,
            "stop_loss": decision.stop_loss,
            "take_profit": tp_primary,
            "risk_reward_ratio": decision.risk_reward_ratio,
            "mirrored_to_binance_testnet": mirrored_ok,
            "binance_mirror_error": mirror_err,
            "thesis": decision.thesis,
            "decision": decision.to_dict(),
        }

    async def get_all_sovereign_decisions(self) -> dict[str, Any]:
        """
        Concurrently synthesizes BTC, ETH, and GOLD into a unified Master Dossier.
        """
        symbols = ["BTC/USDT", "ETH/USDT", "XAU/USD"]
        tasks = [self.synthesize_asset(sym) for sym in symbols]
        results = await asyncio.gather(*tasks, return_exceptions=True)

        decisions_map: dict[str, Any] = {}
        for sym, res in zip(symbols, results):
            if isinstance(res, Exception):
                decisions_map[sym] = {"error": str(res), "action": "CASH"}
            else:
                decisions_map[sym] = res.to_dict()

        return {
            "agent_id": self.agent_id,
            "status": "ONLINE_ACTIVE",
            "tier_1_universe": symbols,
            "timestamp_ms": int(time.time() * 1000),
            "decisions": decisions_map,
        }


